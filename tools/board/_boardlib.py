"""Render a GitHub Projects item list (gh project item-list --format json) as a Markdown snapshot.

Pure functions only; tools/board/export does the I/O.
"""

from __future__ import annotations

import datetime as dt
from collections.abc import Iterable, Mapping
from typing import Any

# Board order of the Status field; unknown statuses go last, in name order.
STATUS_ORDER = ("In progress", "This week", "Blocked", "Next", "Inbox", "Paused", "Done", "Dropped")
NO_STATUS = "(no status)"
COLUMNS = ("Title", "Area", "Due", "Week", "Estimate", "Link")


def _cell(value: Any) -> str:
    """Make a value safe for one Markdown table cell."""
    if value is None:
        return ""
    text = str(value).replace("\r", " ").replace("\n", " ").replace("|", "\\|").strip()
    return text


def _estimate(item: Mapping[str, Any]) -> str:
    for key, value in item.items():
        if key.lower().startswith("estimate") and value not in (None, ""):
            number = float(value)
            return f"{number:g} h"
    return ""


def _week(item: Mapping[str, Any]) -> str:
    week = item.get("week")
    if isinstance(week, Mapping):
        return str(week.get("title") or "")
    return str(week or "")


def _link(item: Mapping[str, Any]) -> str:
    content = item.get("content") or {}
    url = content.get("url")
    if not url:
        return "draft"
    repo = str(content.get("repository") or "").split("/")[-1]
    number = content.get("number")
    label = f"{repo}#{number}" if repo and number is not None else url
    return f"[{_cell(label)}]({url})"


def _status_key(status: str) -> tuple[int, str]:
    if status in STATUS_ORDER:
        return (STATUS_ORDER.index(status), status)
    return (len(STATUS_ORDER), status)


def _row(item: Mapping[str, Any]) -> str:
    cells = (
        _cell(item.get("title")),
        _cell(item.get("area")),
        _cell(item.get("due")),
        _cell(_week(item)),
        _estimate(item),
        _link(item),
    )
    return "| " + " | ".join(cells) + " |"


def render(items: Iterable[Mapping[str, Any]], now: dt.datetime, project_url: str = "") -> str:
    """Return the Markdown snapshot. ``now`` must be timezone-aware."""
    if now.tzinfo is None:
        raise ValueError("now must be timezone-aware")
    groups: dict[str, list[Mapping[str, Any]]] = {}
    for item in items:
        status = str(item.get("status") or NO_STATUS)
        groups.setdefault(status, []).append(item)

    lines = [f"snapshot: {now.isoformat(timespec='minutes')}", ""]
    lines.append("# Board snapshot")
    lines.append("")
    source = f" ({project_url})" if project_url else ""
    lines.append(f"Generated by `tools/board/export` from the GitHub Project{source}. The board is the source of truth;")
    lines.append("this file is a read-only copy for tools that cannot read GitHub Projects.")
    total = sum(len(v) for v in groups.values())
    counts = ", ".join(f"{s} {len(groups[s])}" for s in sorted(groups, key=_status_key))
    lines.append("")
    lines.append(f"{total} items: {counts}." if total else "0 items.")

    for status in sorted(groups, key=_status_key):
        rows = sorted(groups[status], key=lambda i: (str(i.get("due") or "9999"), str(i.get("title") or "")))
        lines += ["", f"## {status} ({len(rows)})", ""]
        lines.append("| " + " | ".join(COLUMNS) + " |")
        lines.append("|" + "---|" * len(COLUMNS))
        lines += [_row(i) for i in rows]
    return "\n".join(lines) + "\n"
